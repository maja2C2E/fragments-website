<!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">What damage reveals.</h2>
<!-- /wp:heading -->

<!-- wp:paragraph {"className":"damage-lead"} -->
<p class="damage-lead">Cracks, separated walls and local collapses are different parts of a building's response to an earthquake.</p>
<!-- /wp:paragraph -->

