<p>Frédéric Dubois holds a PhD in mechanics from the Université de la Méditerranée. He is a research engineer at the French National Centre for Scientific Research (CNRS) and Deputy Director of the Laboratory of Mechanics and Civil Engineering (LMGC) in Montpellier.</p>
<!-- /wp:paragraph -->
<!-- wp:paragraph -->
<p>He is the architect and principal developer of <strong>LMGC90</strong>, an open-source software package for modelling interacting multi-body systems with multiple physics coupling. He received the <strong>CNRS Cristal award in 2007</strong> in recognition of his work on the software.</p>
<!-- /wp:paragraph -->
<!-- wp:paragraph -->
<p>His expertise spans computational mechanics, contact mechanics, fracture and non-smooth dynamics, with applications in masonry structures, architectural heritage and material behaviour. He supervises PhD research and participates in numerous research projects, including work related to the restoration of Notre-Dame Cathedral through the MAESTRO research group associated with CNRS and the French Ministry of Culture.</p>
