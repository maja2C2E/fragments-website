<!-- /wp:paragraph -->
<!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">Post-fire structural assessment.</h2>
<!-- /wp:heading -->
</div>
<!-- /wp:group -->
<!-- wp:group {"layout":{"type":"default"}} -->
<div class="wp-block-group">
<!-- wp:paragraph -->
<p>The fire on April 15, 2019, caused major damage to Notre-Dame Cathedral in Paris: the destruction of the timber roof framework; the collapse of vault sections into the nave following the fall of the spire; cracks in the vaults and buttress walls; and residual displacements resulting from thermal expansion.</p>
<!-- /wp:paragraph -->
<!-- wp:paragraph -->
<p>To support the restoration, the French State established a public institution dedicated to the conservation and restoration of Notre-Dame (EP RNDP), while the CNRS and the Ministry of Culture coordinated a scientific project involving experts in stone, wood, metal, glass, acoustics, digital technologies, and structural engineering. Within the “structure” working group, the objectives are to understand the mechanical behavior of the Gothic cathedral, assess its strength and resilience, and develop advanced 3D numerical models to analyze the complex interactions between the vaults, flying buttresses, nave walls, buttresses, and supports.</p>
<!-- /wp:paragraph -->
<!-- wp:paragraph -->
<p>The lecture will address three main aspects:</p>
<!-- /wp:paragraph -->
<!-- wp:list -->
<ul class="wp-block-list"><!-- wp:list-item -->
<li>The original structural behavior of the cathedral.</li>
<!-- /wp:list-item --><!-- wp:list-item -->
<li>The impact of the fire.</li>
<!-- /wp:list-item --><!-- wp:list-item -->
<li>The effect of the new roof framework on the stability of the masonry under wind loads.</li>
<!-- /wp:list-item --></ul>
<!-- /wp:list -->
</div>
